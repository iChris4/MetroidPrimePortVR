#!/usr/bin/env python3
"""Regenerates platform/port_disc_verify_table.inc: per supported disc revision,
its size, SHA-1 and the CRC32 of every 1 MiB chunk (the last one partial), for
the in-app disc image check (platform/port_disc_verify.cpp).

    python3 -I tools/disc_chunk_table.py [--out platform/port_disc_verify_table.inc] \
        usa100.iso usa101.iso usa102.iso pal.iso

Give each image as an uncompressed Redump ISO (any order); the revision is read
from the header (game id at 0x0, version byte at 0x7). Only these four are
accepted, and the SHA-1s below must match Redump's.
"""
import hashlib
import sys
import zlib

CHUNK = 1 << 20
REVISIONS = {
    (b"GM8E01", 0): ("USA 1.00", "ac20c744db18fdf0339f37945e880708fd317231"),
    (b"GM8E01", 1): ("USA 1.01", "4ba8933499e0b74b2f6006d622e4fbc7593ab3c7"),
    (b"GM8E01", 2): ("USA 1.02", "1a737910b55b59c6ad91be9e3e3c43517fd52efb"),
    (b"GM8P01", 0): ("PAL", "34ac8a764a3c1db3326c39071cee2fc49e730aca"),
}
ORDER = [("GM8E01", 0), ("GM8E01", 1), ("GM8E01", 2), ("GM8P01", 0)]


def scan(path):
    sha = hashlib.sha1()
    crcs = []
    size = 0
    head = b""
    with open(path, "rb") as f:
        while True:
            buf = f.read(CHUNK)
            if not buf:
                break
            if not head:
                head = buf[:8]
            sha.update(buf)
            crcs.append(zlib.crc32(buf) & 0xFFFFFFFF)
            size += len(buf)
    return head, size, sha.hexdigest(), crcs


def main(argv):
    out = "platform/port_disc_verify_table.inc"
    args = argv[1:]
    if args[:1] == ["--out"]:
        out, args = args[1], args[2:]
    found = {}
    for path in args:
        head, size, sha, crcs = scan(path)
        key = (head[:6], head[7])
        if key not in REVISIONS:
            sys.exit(f"{path}: not a supported disc ({head[:6]!r}, version {head[7]})")
        name, want = REVISIONS[key]
        if sha != want:
            sys.exit(f"{path}: SHA-1 {sha} is not Redump's {want} for {name}")
        found[(key[0].decode(), key[1])] = (name, size, sha, crcs)
    missing = [k for k in ORDER if k not in found]
    if missing:
        sys.exit(f"missing images for {missing}")
    lines = [
        "// Generated by tools/disc_chunk_table.py from the Redump images; do not edit.",
        "// Regenerate: python3 -I tools/disc_chunk_table.py usa100.iso usa101.iso usa102.iso pal.iso",
        "// Per revision: game id, version byte, name, size, SHA-1, then the CRC32 of each 1 MiB chunk.",
    ]
    for key in ORDER:
        name, size, sha, crcs = found[key]
        lines.append(f'{{"{key[0]}", {key[1]}, "{name}", {size}ull, "{sha}", {len(crcs)}, {{')
        for i in range(0, len(crcs), 10):
            lines.append("    " + ", ".join(f"0x{c:08x}" for c in crcs[i:i + 10]) + ",")
        lines.append("}},")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")


main(sys.argv)
